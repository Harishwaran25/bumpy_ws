def create_logo_image():
    """Create a PIL Image from the logo bitmap data"""
    # Logo dimensions from the data (128x64 pixels)
    width, height = 128, 64
    
    # Create a monochrome image (mode '1' is 1-bit pixels, black and white)
    image = Image.new('1', (width, height))
    
    # Process the bitmap data and set pixels
    # OLED displays typically have 0 for black (off) and 1 for white (on)
    # But our bitmap data has 0xFF for white, so we need to invert the bits
    for y in range(height):
        for x in range(width):
            byte_index = y * (width // 8) + (x // 8)
            if byte_index < len(LOGO_DATA):
                bit_position = 7 - (x % 8)  # Bit ordering in the byte
                pixel_value = (LOGO_DATA[byte_index] >> bit_position) & 1
                # Invert the pixel value (1 for white, 0 for black)
                image.putpixel((x, y), pixel_value)
    
    return image

def check_connection():
    """Check if connected to the internet"""
    try:
        # Try to connect to Google's DNS
        socket.create_connection(("8.8.8.8", 53), timeout=3)
        return True
    except OSError:
        return False

def get_ip_address():
    """Get the IP address of the Raspberry Pi"""
    try:
        # Try getting wireless IP
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        s.connect(("8.8.8.8", 80))
        ip = s.getsockname()[0]
        s.close()
        return ip
    except:
        try:
            # Try different interfaces if the above fails
            for interface in ['wlan0', 'eth0', 'usb0']:
                ip = os.popen(f'ip addr show {interface} | grep "\<inet\>" | awk \'{{print $2}}\' | awk -F "/" \'{{print $1}}\'').read().strip()
                if ip and ip != "127.0.0.1":
                    return ip
        except:
            pass
        
        return "No IP found"

def main():
    # Setup logging
    log_file = '/home/bumpy1/ip_display.log'
    
    try:
        # Initialize the I2C interface
        serial = i2c(port=1, address=0x3C)  # Change address if needed
        
        # Initialize the OLED display
        device = ssd1306(serial, width=128, height=64)
        
        # Try to load a font, fallback to default if not available
        try:
            font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 14)
            small_font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 10)
        except IOError:
            font = ImageFont.load_default()
            small_font = ImageFont.load_default()
        
        # Create the logo image
        logo_image = create_logo_image()
        
        # Display the logo for 4 seconds
        device.display(logo_image)
        time.sleep(4)
        
        # Get hostname
        hostname = socket.gethostname()
        
        # Wait for internet connection - with animation
        dots = 0
        connection_start_time = time.time()
        
        # Show "Connecting" until connected or timeout (30 seconds)
        while not check_connection():
            with canvas(device) as draw:
                # Draw a border
                draw.rectangle(device.bounding_box, outline="white", fill="black")
                
                # Display the hostname centered
                hostname_width = draw.textlength(hostname, font=font)
                draw.text(((device.width - hostname_width) // 2, 2), f"{hostname}", fill="white", font=font)
                
                # Display connecting message with animated dots
                connecting_text = "Connecting to WiFi" + "." * dots
                draw.text((4, 30), connecting_text, fill="white", font=font)
                
                # Show Karthikesh Robotics
                draw.text((4, 50), "Karthikesh Robotics", fill="white", font=small_font)
            
            # Update dots animation
            dots = (dots + 1) % 4
            
            # Check if we've waited 30 seconds for connection
            if time.time() - connection_start_time > 30:
                # Show "No Connection" for 5 seconds then exit
                for i in range(5):
                    with canvas(device) as draw:
                        draw.rectangle(device.bounding_box, outline="white", fill="black")
                        # Display the hostname centered
                        hostname_width = draw.textlength(hostname, font=font)
                        draw.text(((device.width - hostname_width) // 2, 2), f"{hostname}", fill="white", font=font)
                        
                        # Display "No WiFi Connection" centered
                        no_wifi_text = "No WiFi Connection"
                        no_wifi_width = draw.textlength(no_wifi_text, font=font)
                        draw.text(((device.width - no_wifi_width) // 2, 30), no_wifi_text, fill="white", font=font)
                        draw.text((4, 50), "Karthikesh Robotics", fill="white", font=small_font)
                    time.sleep(1)
                device.clear()
                return
            
            time.sleep(0.5)
        
        # Get the IP address once connected
        ip_address = get_ip_address()
        with open(log_file, 'w') as f:
            f.write(f"Connected! IP Address: {ip_address}\n")
        
        # Display IP for exactly 30 seconds
        display_start_time = time.time()
        
        while time.time() - display_start_time < 30:
            with canvas(device) as draw:
                # Draw a border
                draw.rectangle(device.bounding_box, outline="white", fill="black")
                
                # Display the hostname
                draw.text((4, 2), f"{hostname}", fill="white", font=font)
                
                # Display "IP Address:" text centered
                ip_label_width = draw.textlength("IP Address", font=small_font)
                draw.text(((device.width - ip_label_width) // 2, 22), "IP Address", fill="white", font=small_font)
                
                # Display the IP address centered
                ip_width = draw.textlength(ip_address, font=font)
                draw.text(((device.width - ip_width) // 2, 37), f"{ip_address}", fill="white", font=font)
                
            
            # Update every 1 second
            time.sleep(1)
    
    except Exception as e:
        # Log any errors
        with open(log_file, 'w') as f:
            f.write(f"Error: {str(e)}\n")
    
    finally:
        # Clear the display before exiting
        try:
            device.clear()
        except:
            pass

if __name__ == "__main__":
    main()
